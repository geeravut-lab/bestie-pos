/** Back-office pages by path. Mounted by apps/pos and apps/admin through `AuthApp pages={adminPages}`. */
export function adminPages(ctx: PageContext): ReactNode | null {
  if (ctx.path === '/admin/audit' || ctx.path.startsWith('/admin/audit/'))
    return <AuditPage ctx={ctx} />;
  if (ctx.path === '/admin/branding' || ctx.path.startsWith('/admin/branding/'))
    return <BrandingPage ctx={ctx} />;
  if (ctx.path === '/ai/usage') return <AiUsagePage ctx={ctx} />;
  if (ctx.path === '/calendar') return <AppointmentsPage ctx={ctx} />;
  if (ctx.path === '/folio') return <FolioPage ctx={ctx} />;
  if (ctx.path === '/karaoke') return <KaraokePage ctx={ctx} />;
  if (ctx.path === '/karaoke/bookings') return <KaraokeBookingsPage ctx={ctx} />;
  const playerRoom = karaokePlayerRoomFromPath(ctx.path);
  if (playerRoom) return <KaraokePlayerPage ctx={ctx} roomId={playerRoom} />;
  if (ctx.path === '/translate') return <TranslatePage ctx={ctx} />;
  if (ctx.path === '/commission') return <CommissionPage ctx={ctx} />;
  if (ctx.path === '/packages') return <PackagesPage ctx={ctx} />;
  if (ctx.path === '/labels') return <LabelsPage ctx={ctx} />;
  if (ctx.path === '/resources') return <ResourcesPage ctx={ctx} />;
  if (ctx.path === '/hair-styles') return <HairStylesPage ctx={ctx} />;
  if (ctx.path === '/spa-advisor') return <SpaAdvisorPage ctx={ctx} />;
  if (ctx.path === '/settings/accounting') return <AccountingPage ctx={ctx} />;
  if (ctx.path === '/network') return <NetworkPage ctx={ctx} />;
  if (ctx.path === '/days-off') return <DaysOffPage ctx={ctx} />;
  if (ctx.path === '/group-booking') return <GroupBookingPage ctx={ctx} />;
  if (ctx.path === '/ask') return <AskShopPage ctx={ctx} />;
  if (ctx.path === '/feedback') return <FeedbackPage ctx={ctx} />;
  if (ctx.path === '/settings/info') return <ShopInfoPage ctx={ctx} />;
  if (ctx.path === '/admin/line') return <LineSettingsPage ctx={ctx} />;
  if (ctx.path === '/admin/cards') return <CardImagesPage ctx={ctx} />;
  if (ctx.isPlatformAdmin && ctx.path === '/ai')
    return <AiSettingsPage ctx={ctx} onNavigate={ctx.navigate} />;
  if (ctx.path === '/admin/ai/prompts')
    return <AiPromptsPage ctx={ctx} onNavigate={ctx.navigate} />;
  if (ctx.path === '/settings/billing') return <BillingPage ctx={ctx} />;
  if (ctx.path === '/settings/theme') return <ThemePage ctx={ctx} />;
  if (ctx.path === '/settings/tenders') return <TendersPage ctx={ctx} />;
  if (ctx.path === '/menu') return <MenuPage ctx={ctx} />;
  if (ctx.path === '/modules') return <ModulesPage ctx={ctx} />;
  if (ctx.path === '/staff') return <StaffPage ctx={ctx} />;
  if (ctx.path === '/stock') return <StockPage ctx={ctx} />;
  if (ctx.path === '/staff/roles') return <RolesPage ctx={ctx} />;
  if (ctx.path === '/crypto') return <CryptoPage ctx={ctx} />;
  if (ctx.path === '/customers') return <CustomersPage ctx={ctx} />;
  if (ctx.path === '/reports') return <ReportsPage ctx={ctx} />;
  if (ctx.path === '/devices') return <DevicesPage ctx={ctx} />;
  return null;
}
