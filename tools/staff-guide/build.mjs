const b64 = (p) => readFileSync(p).toString('base64');
const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
const img = (name) => {
  const p = join(here, 'shots', `${name}.jpg`);
  if (!existsSync(p)) throw new Error(`missing screenshot ${name}`);
  return `data:image/jpeg;base64,${b64(p)}`;
};

// ── building blocks ──────────────────────────────────────────────────────────────────────────
let figNo = 0;
const fig = (name, cap) =>
  `<figure><div class="frame"><img src="${img(name)}"></div><figcaption><b>${++figNo}</b> ${cap}</figcaption></figure>`;
/** tablet screens, 2 per row */
const shotsT = (items) => `<div class="shots t">${items.map(([n, c]) => fig(n, c)).join('')}</div>`;
/** phone screens, 4 per row */
const shotsP = (items) => `<div class="shots p">${items.map(([n, c]) => fig(n, c)).join('')}</div>`;
/** small-tablet screens, 3 per row */
const shotsM = (items) => `<div class="shots m">${items.map(([n, c]) => fig(n, c)).join('')}</div>`;
const p = (t) => `<p>${t}</p>`;
const ul = (items) => `<ul>${items.map((x) => `<li>${x}</li>`).join('')}</ul>`;
const ol = (items) => `<ol>${items.map((x) => `<li>${x}</li>`).join('')}</ol>`;
const note = (t, cls = '') => `<div class="note ${cls}">${t}</div>`;
const h3 = (t) => `<h3>${esc(t)}</h3>`;
const table = (head, rows, cls = '') =>
  `<table class="${cls}"><thead><tr>${head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows
    .map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join('')}</tr>`)
    .join('')}</tbody></table>`;
/** Two-lane flow: [lane, text]; lane 0 = person doing it, 1 = system / other role. */
const flow = (steps, lanes) =>
  `<table class="lane"><thead><tr><th class="c0">${esc(lanes[0])}</th><th class="c1">${esc(lanes[1])}</th></tr></thead><tbody>${steps
    .map(
      ([lane, text], i) =>
        `<tr>${[0, 1]
          .map((l) =>
            l === lane
              ? `<td><span class="dot c${l}">${i + 1}</span>${text}</td>`
              : '<td class="empty"></td>',
          )
          .join('')}</tr>`,
    )
    .join('')}</tbody></table>`;
const chap = (title, body) => `<section class="chap"><h1>${esc(title)}</h1>${body}</section>`;
const dev = (t) => `<span class="dev">${esc(t)}</span>`;

