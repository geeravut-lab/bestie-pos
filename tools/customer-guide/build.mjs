const fontDir = join(
  root,
  'node_modules/.pnpm/@fontsource-variable+noto-sans-thai@5.3.0/node_modules/@fontsource-variable/noto-sans-thai/files',
);
const b64 = (p) => readFileSync(p).toString('base64');
const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
const img = (name) => {
  const p = join(here, 'shots', `${name}.jpg`);
  if (!existsSync(p)) throw new Error(`missing screenshot ${name}`);
  return `data:image/jpeg;base64,${b64(p)}`;
};

// ── building blocks ──────────────────────────────────────────────────────────────────────────
let figNo = 0;
/** A row of numbered screenshots with captions. kind: 'phone' (tall, cropped) or 'tablet' (wide). */
const shots = (items, kind = 'phone') =>
  `<div class="shots ${kind === 'wide' ? 'wide' : `phone n${items.length > 3 ? 4 : 3} ${kind === 'tall' ? 'tall' : ''}`}">${items
    .map(
      ([name, cap]) =>
        `<figure><div class="frame"><img src="${img(name)}"></div><figcaption><b>${++figNo}</b> ${esc(cap)}</figcaption></figure>`,
    )
    .join('')}</div>`;
const p = (t) => `<p>${t}</p>`;
const ul = (items) => `<ul>${items.map((x) => `<li>${x}</li>`).join('')}</ul>`;
const note = (t, cls = '') => `<div class="note ${cls}">${t}</div>`;
const h3 = (t) => `<h3>${esc(t)}</h3>`;
const table = (head, rows, cls = '') =>
  `<table class="${cls}"><thead><tr>${head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows
    .map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join('')}</tr>`)
    .join('')}</tbody></table>`;
/** Two-lane flow: [lane, text] steps; lane 0 = customer, 1 = shop / system. */
const flow = (steps, lanes = ['ลูกค้า', 'ร้าน / ระบบ']) =>
  `<table class="lane"><thead><tr><th class="c0">${lanes[0]}</th><th class="c1">${lanes[1]}</th></tr></thead><tbody>${steps
    .map(
      ([lane, text], i) =>
        `<tr>${[0, 1]
          .map((l) =>
            l === lane
              ? `<td><span class="dot c${l}">${i + 1}</span>${text}</td>`
              : '<td class="empty"></td>',
          )
          .join('')}</tr>`,
    )
    .join('')}</tbody></table>`;
const section = (title, body, cls = '') =>
  `<section class="chap ${cls}"><h1>${esc(title)}</h1>${body}</section>`;

